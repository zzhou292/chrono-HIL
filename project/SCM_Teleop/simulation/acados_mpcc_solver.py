"""
acados_mpcc_solver.py
=====================

Model Predictive Contouring Control (MPCC) for an HMMWV on Soil
Contact Model (SCM) terrain.

Why MPCC (and what's different from the standard MPC in
``acados_mpc_solver.py``)
--------------------------------------------------------------
The standard formulation tracks a *time-parametrised* reference
``(x_ref(t), y_ref(t), ψ_ref(t), v_ref(t))``.  The reference speed
``v_ref(t)`` is generated by ``reference_path.py`` from path
curvature alone — it ignores the *friction ellipse* (longitudinal
and lateral tire-force budgets share the same μ·g envelope) and is
pre-computed open-loop.  In closed-loop driving on low-traction
SCM terrain (clay μ ≈ 0.23 → ay_max ≈ 2.3 m/s²), the reference is
often *infeasible*: the speed profile assumes a constant
``a_brake = 2.0 m/s²`` and ``a_accel = 3.0 m/s²`` *independent* of
lateral demand, but at cornering near ay_max the longitudinal
authority is essentially zero.  The MPC ends up fighting itself —
chasing an unreachable v_ref and sacrificing path tracking.

MPCC drops the speed reference entirely.  The path is just the
*spatial* curve ``(x_p(θ), y_p(θ))``.  ``θ`` (arc-length along the
path) is added to the state, and ``vθ = θ̇`` becomes a *control
input*.  The optimizer picks ``vθ`` itself, subject to:

* dynamics (bicycle + NN-surrogate Fy);
* actuator bounds;
* the *friction ellipse*:
  ``(Fx_total / Fx_max)² + (Fy_total / Fy_max)² ≤ 1``
  evaluated symbolically on NN tire forces at every stage.

Cost (NO speed reference):

    J = Σ_k [ w_c · e_c²(k) + w_l · e_l²(k) − w_prog · vθ(k)
              + control regularisation(k) ]

with the contour and lag errors

    e_c =  (px − x_p(θ)) · sin(ψ_p) − (py − y_p(θ)) · cos(ψ_p)   (lateral)
    e_l = −(px − x_p(θ)) · cos(ψ_p) − (py − y_p(θ)) · sin(ψ_p)   (longitudinal)

and the progress reward ``−w_prog · vθ``.  In a curve, the friction
ellipse binds, capping ``vθ``; on a straight, the optimizer pushes
``vθ`` up to the actuator limit.  This is the same formulation
used in Liniger et al. (2015) and the F1Tenth racing MPC stack.

Path representation
-------------------
The full path ``(x_p(θ), y_p(θ), ψ_p(θ))`` is a cubic spline in
``ReferencePath``.  We can't embed a spline inside CasADi directly,
so at each solve the controller node samples the spline at the
*predicted* θ trajectory (warm-started from last solve) and passes
the four parameters ``(x_p_k, y_p_k, sin_ψ_p_k, cos_ψ_p_k)`` per
stage.  One outer iteration is enough in practice — the predicted
θ trajectory rarely diverges far from the actual one because
``θ̇ = vθ`` is bounded.

State / control / parameter layout
----------------------------------
State (10):  [x, y, ψ, u, v, ω, ax, δ_prev, Jx_prev, θ]
Control (3): [δ, Jx, vθ]
Parameters per stage (small + interpretable):
  (x_p, y_p, sin_ψ_p, cos_ψ_p,
   Kphi, Kc, n_terrain, c, phi (rad), k_janosi)
"""

